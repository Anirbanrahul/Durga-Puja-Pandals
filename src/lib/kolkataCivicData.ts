/**
 * Returns currently active Durga Puja Tithi based on system time or festival calendar
 */
export function getCurrentPujoTithi(): PujoTithiInfo {
  const now = new Date();
  const day = now.getDate();
  const month = now.getMonth(); // 9 is October (0-indexed)

  if (month === 9) {
    if (day <= 16) return { ...PUJO_2026_SCHEDULE[0], status: 'Running Now' };
    if (day === 17) return { ...PUJO_2026_SCHEDULE[1], status: 'Running Now' };
    if (day === 18) return { ...PUJO_2026_SCHEDULE[2], status: 'Running Now' };
    if (day === 19) return { ...PUJO_2026_SCHEDULE[3], status: 'Running Now' };
    if (day >= 20) return { ...PUJO_2026_SCHEDULE[4], status: 'Running Now' };
  }

  // Fallback to Maha Saptami as the default festive active tithi
  return { ...PUJO_2026_SCHEDULE[1], status: 'Running Now' };
}
